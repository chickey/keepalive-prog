#!/usr/bin/env python3
"""Sign Keep Alive firmware for the update loader, and build factory images.

  kasign.py keygen ~/.eplop/keepalive-primary.pem
  kasign.py pubkey ~/.eplop/keepalive-primary.pem          (prints the public key)
  kasign.py keys-h firmware/loader/keys.h PRIMARY.pem|HEX BACKUP.pem|HEX
  kasign.py sign keepalive.bin keepalive.kai --key KEY.pem --key-id 0 --version 1.1.0 [--sec-level 0]
  kasign.py verify keepalive.kai --keys firmware/loader/keys.h
  kasign.py factory loader.bin [keepalive.kai] -o factory.bin

The .kai file is the 128-byte header followed by the firmware image; the
layout matches firmware/src/image.h. The signature (Ed25519) covers the first
64 header bytes and the image, so the version and length are signed too.

Private keys never go in the repository. Keep the primary somewhere safe
(password manager) and the backup offline: if both are lost, Keep Alives in
the field can only be updated by holding BOOT and using WCH's bootloader.
"""
import argparse, os, re, struct, sys, zlib

from cryptography.hazmat.primitives import serialization as ser
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey
from cryptography.exceptions import InvalidSignature

IMG_MAGIC = 0x3149414B   # "KAI1"
HDR_VERSION = 1
LOADER_MAX = 0x3F00
IMG_HDR_OFF = 0x3F00
APP_OFF = 0x4000
APP_MAX = 0xF700 - APP_OFF
HDR_FMT = "<IIII16sIIII16s64s"
assert struct.calcsize(HDR_FMT) == 128


def load_private(path):
    with open(os.path.expanduser(path), "rb") as f:
        pw = os.environ.get("KASIGN_PASSWORD")
        return ser.load_pem_private_key(f.read(), password=pw.encode() if pw else None)


def raw_public(k):
    return k.public_key().public_bytes(ser.Encoding.Raw, ser.PublicFormat.Raw)


def public_from(arg):
    if re.fullmatch(r"[0-9a-fA-F]{64}", arg):
        return bytes.fromhex(arg)
    return raw_public(load_private(arg))


def parse_header(data):
    if len(data) < 128:
        raise SystemExit("file too short for a header")
    f = struct.unpack(HDR_FMT, data[:128])
    return dict(magic=f[0], hdr_version=f[1], length=f[2], load_off=f[3],
                version=f[4].rstrip(b"\0").decode(), sec_level=f[5], key_id=f[6],
                crc32=f[7], flags=f[8], sig=f[10])


def cmd_keygen(a):
    path = os.path.expanduser(a.out)
    if os.path.exists(path):
        raise SystemExit(f"{path} already exists; not overwriting a signing key")
    os.makedirs(os.path.dirname(path) or ".", mode=0o700, exist_ok=True)
    k = Ed25519PrivateKey.generate()
    pw = os.environ.get("KASIGN_PASSWORD")
    enc = ser.BestAvailableEncryption(pw.encode()) if pw else ser.NoEncryption()
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(k.private_bytes(ser.Encoding.PEM, ser.PrivateFormat.PKCS8, enc))
    print(raw_public(k).hex())


def cmd_pubkey(a):
    print(public_from(a.key).hex())


def cmd_keys_h(a):
    keys = [public_from(k) for k in a.keys]
    lines = ["// Public keys the loader accepts firmware from (generated by tools/kasign.py keys-h).",
             "// Key 0 signs releases; key 1 is the offline backup, for replacing key 0 if it",
             "// is ever lost or leaked. Changing these needs a new loader, i.e. the factory.",
             "#define NKEYS %d" % len(keys),
             "static const uint8_t pubkeys[NKEYS][32] = {"]
    for k in keys:
        lines.append("\t{ " + ", ".join(f"0x{b:02x}" for b in k) + " },")
    lines.append("};")
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{a.out}: {len(keys)} keys")


def cmd_sign(a):
    img = open(a.image, "rb").read()
    img += b"\xff" * (-len(img) % 4)
    if len(img) > APP_MAX:
        raise SystemExit(f"image is {len(img)} bytes; at most {APP_MAX} fit")
    ver = a.version.encode()
    if len(ver) > 15:
        raise SystemExit("version too long (15 characters at most)")
    k = load_private(a.key)
    head = struct.pack("<IIII16sIIII16s", IMG_MAGIC, HDR_VERSION, len(img), APP_OFF, ver,
                       a.sec_level, a.key_id, zlib.crc32(img), 0, bytes(16))
    sig = k.sign(head + img)
    with open(a.out, "wb") as f:
        f.write(head + sig + img)
    print(f"{a.out}: {ver.decode()} {len(img)} bytes, key {a.key_id} ({raw_public(k).hex()[:16]}…)")


def read_keys_h(path):
    txt = open(path).read()
    return [bytes(int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", row))
            for row in re.findall(r"\{([^{}]*0x[^{}]*)\}", txt.split("pubkeys", 1)[1])]


def check(data, keys):
    h = parse_header(data)
    img = data[128:]
    problems = []
    if h["magic"] != IMG_MAGIC: problems.append("bad magic")
    if h["hdr_version"] != HDR_VERSION: problems.append("unknown header version")
    if h["load_off"] != APP_OFF: problems.append("wrong load address")
    if h["length"] != len(img) or len(img) % 4 or len(img) > APP_MAX: problems.append("bad length")
    if zlib.crc32(img) != h["crc32"]: problems.append("CRC mismatch")
    if h["key_id"] >= len(keys):
        problems.append("unknown key")
    else:
        try:
            Ed25519PublicKey.from_public_bytes(keys[h["key_id"]]).verify(h["sig"], data[:64] + img)
        except InvalidSignature:
            problems.append("signature does not verify")
    return h, problems


def cmd_verify(a):
    h, problems = check(open(a.image, "rb").read(), read_keys_h(a.keys))
    print(f"{a.image}: version {h['version']}, {h['length']} bytes, key {h['key_id']}, sec {h['sec_level']}")
    if problems:
        raise SystemExit("NOT VALID: " + ", ".join(problems))
    print("signature OK")


def cmd_factory(a):
    ldr = open(a.loader, "rb").read()
    if len(ldr) > LOADER_MAX:
        raise SystemExit(f"loader is {len(ldr)} bytes; at most {LOADER_MAX} fit")
    out = ldr
    if a.image:
        data = open(a.image, "rb").read()
        if a.keys:
            _, problems = check(data, read_keys_h(a.keys))
            if problems:
                raise SystemExit("firmware image NOT VALID: " + ", ".join(problems))
        out = ldr + b"\xff" * (IMG_HDR_OFF - len(ldr)) + data[:128] + b"\xff" * (APP_OFF - IMG_HDR_OFF - 128) + data[128:]
    with open(a.o, "wb") as f:
        f.write(out)
    print(f"{a.o}: {len(out)} bytes ({'loader + firmware' if a.image else 'loader only'})")


def cmd_site(a):
    """Copy the signed firmware and the full factory image to the web flasher, with a manifest."""
    import datetime, hashlib, json, shutil
    src = lambda n: os.path.join(a.prebuilt, n)
    kai = open(src("keepalive.kai"), "rb").read()
    h, problems = check(kai, read_keys_h(a.keys))
    if problems:
        raise SystemExit("prebuilt/keepalive.kai NOT VALID: " + ", ".join(problems))
    full = open(src("factory-full.bin"), "rb").read()
    if full[APP_OFF:] != kai[128:] or full[IMG_HDR_OFF:IMG_HDR_OFF + 128] != kai[:128]:
        raise SystemExit("prebuilt/factory-full.bin doesn't hold prebuilt/keepalive.kai; run make prebuilt")
    m = re.search(rb"ldr=([0-9A-Za-z.\-]+)", full[:LOADER_MAX])
    shutil.copyfile(src("keepalive.kai"), os.path.join(a.out, "keepalive.kai"))
    shutil.copyfile(src("factory-full.bin"), os.path.join(a.out, "keepalive-full.bin"))
    built = datetime.date.fromtimestamp(os.path.getmtime(src("keepalive.kai"))).isoformat()
    manifest = {
        "name": "Keep Alive",
        "version": h["version"],
        "file": "keepalive.kai",
        "size": len(kai),
        "sha256": hashlib.sha256(kai).hexdigest(),
        "built": built,
        "chip": "CH32X035F8U6",
        "loader": m.group(1).decode() if m else None,
        "full": {"file": "keepalive-full.bin", "size": len(full), "sha256": hashlib.sha256(full).hexdigest()},
        "note": a.note,
    }
    with open(os.path.join(a.out, "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")
    print(f"{a.out}: firmware {h['version']} ({len(kai)} bytes), loader {manifest['loader']}")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = p.add_subparsers(dest="cmd", required=True)
    s = sp.add_parser("keygen"); s.add_argument("out"); s.set_defaults(f=cmd_keygen)
    s = sp.add_parser("pubkey"); s.add_argument("key"); s.set_defaults(f=cmd_pubkey)
    s = sp.add_parser("keys-h"); s.add_argument("out"); s.add_argument("keys", nargs="+"); s.set_defaults(f=cmd_keys_h)
    s = sp.add_parser("sign"); s.add_argument("image"); s.add_argument("out")
    s.add_argument("--key", required=True); s.add_argument("--key-id", type=int, default=0)
    s.add_argument("--version", required=True); s.add_argument("--sec-level", type=int, default=0)
    s.set_defaults(f=cmd_sign)
    s = sp.add_parser("verify"); s.add_argument("image"); s.add_argument("--keys", required=True); s.set_defaults(f=cmd_verify)
    s = sp.add_parser("factory"); s.add_argument("loader"); s.add_argument("image", nargs="?")
    s.add_argument("-o", required=True); s.add_argument("--keys"); s.set_defaults(f=cmd_factory)
    s = sp.add_parser("site"); s.add_argument("prebuilt"); s.add_argument("out")
    s.add_argument("--keys", required=True); s.add_argument("--note", default=""); s.set_defaults(f=cmd_site)
    a = p.parse_args()
    a.f(a)


if __name__ == "__main__":
    main()
